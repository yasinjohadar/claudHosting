$dialRows = require __DIR__.'/data/international_dial_codes.php';

$flagEmoji = static function (string $iso): string {
    $iso = strtoupper($iso);
    if (strlen($iso) !== 2) {
        return '';
    }
    $o0 = ord($iso[0]);
    $o1 = ord($iso[1]);
    if ($o0 < 65 || $o0 > 90 || $o1 < 65 || $o1 > 90) {
        return '';
    }
    $a = $o0 - 65 + 0x1F1E6;
    $b = $o1 - 65 + 0x1F1E6;

    return mb_chr($a, 'UTF-8').mb_chr($b, 'UTF-8');
};

