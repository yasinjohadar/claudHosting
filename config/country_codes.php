    $nameAr = $row['name_ar'];
    $isoUpper = strtoupper($row['iso']);
    $emoji = $flagEmoji($isoUpper);
    $listTextOnly[$code] = $nameAr.' ('.$code.')';
    $list[$code] = ($emoji !== '' ? $emoji.' ' : '').$nameAr.' ('.$code.')';
    $iso[$code] = $isoUpper;
}

